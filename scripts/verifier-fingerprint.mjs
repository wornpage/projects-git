import { createHash } from 'node:crypto';
import { readFile, writeFile, realpath } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname, relative, isAbsolute, sep } from 'node:path';
import { isBuiltin } from 'node:module';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const entries = ['src/cloudflare/index.ts', 'src/cloudflare/check-container.ts', 'src/cloudflare/subscription-service.ts', 'scripts/verifier-fingerprint.mjs'];
const pins = ['package.json', 'package-lock.json'];
const generatedIdentity = 'src/cloudflare/verifier-identity.ts';
const canonical = path => process.platform === 'win32' ? path.toLowerCase() : path;
const stamp = sha => `// Generated by scripts/verifier-fingerprint.mjs; hashes the complete verifier source boundary.\nexport const VERIFIER_SHA256 = '${sha}';\n`;

// Runtime source is discovered from the actual entrypoints, not a maintained
// partial list. Type-only imports are erased; guest code remains bound by its
// commit/definition and container code by the separately reported image digest.
async function collectSources(projectRoot) {
  const base = await realpath(projectRoot), sources = new Map();
  const nameOf = path => relative(base, path).replaceAll(sep, '/');
  async function checked(path) {
    const name = relative(base, path);
    if (isAbsolute(name) || name === '..' || name.startsWith('..' + sep)) throw new Error('Verifier import escapes the source root.');
    if (canonical(await realpath(path)) !== canonical(path)) throw new Error('Verifier source is redirected: ' + name);
    return path;
  }
  for (const name of pins) sources.set(name, await readFile(await checked(resolve(base, name))));
  const lock = JSON.parse(sources.get('package-lock.json').toString('utf8'));
  try {
    await build({
      entryPoints: entries.map(name => resolve(base, name)), absWorkingDir: base,
      bundle: true, write: false, outdir: '.verifier-boundary-unused', format: 'esm', platform: 'neutral', treeShaking: false,
      logLevel: 'silent', logOverride: { 'unsupported-dynamic-import': 'error', 'unsupported-require-call': 'error' },
      plugins: [{ name: 'closed-verifier-boundary', setup(context) {
        context.onResolve({ filter: /.*/ }, async args => {
          if (isBuiltin(args.path) || args.path === 'cloudflare:workers') return { path: args.path, external: true };
          if (args.kind === 'entry-point' || args.path.startsWith('.')) {
            const path = args.kind === 'entry-point' ? resolve(base, args.path) : resolve(dirname(args.importer), args.path.split(/[?#]/)[0]);
            // The generated digest cannot be hashed into itself.
            if (nameOf(path) === generatedIdentity) {
              const identity = (await readFile(await checked(path), 'utf8')).replaceAll('\r\n', '\n');
              const sha = /export const VERIFIER_SHA256 = '([a-f0-9]{64})';/.exec(identity)?.[1];
              if (!sha || identity !== stamp(sha)) throw new Error('Generated verifier identity contains unexpected source.');
              return { path, external: true };
            }
            return { path: await checked(path) };
          }
          if (args.path.includes(':') || isAbsolute(args.path)) throw new Error('Verifier import uses an unsupported source location.');
          const parts = args.path.split('/'), packageName = parts[0].startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
          const pin = lock.packages?.['node_modules/' + packageName];
          if (!pin?.version || !pin.integrity) throw new Error('Verifier dependency lacks a locked version and integrity: ' + packageName);
          return { path: args.path, external: true };
        });
        context.onLoad({ filter: /.*/, namespace: 'file' }, async args => {
          const bytes = await readFile(await checked(args.path)), name = nameOf(args.path);
          const loader = /\.[cm]?ts$/.test(name) ? 'ts' : /\.[cm]?js$/.test(name) ? 'js' : name.endsWith('.json') ? 'json' : null;
          if (!loader) throw new Error('Verifier source has an unsupported module type: ' + name);
          sources.set(name, bytes);
          return { contents: new TextDecoder('utf-8', { fatal: true }).decode(bytes), loader };
        });
      } }],
    });
  } catch (error) {
    throw new Error('Verifier dependency discovery failed: ' + (error.errors?.map(item => item.text).join('; ') ?? 'source cannot be parsed'));
  }
  for (const [name, bytes] of sources) {
    if (!bytes.equals(await readFile(await checked(resolve(base, name))))) throw new Error('Verifier source changed during dependency discovery: ' + name);
  }
  return sources;
}

export async function verifierInputs(projectRoot = root) {
  return [...(await collectSources(projectRoot)).keys()].sort();
}

export async function verifierFingerprint(projectRoot = root) {
  const hash = createHash('sha256');
  const sources = await collectSources(projectRoot);
  for (const name of [...sources.keys()].sort()) hash.update(name + '\0').update(sources.get(name));
  return hash.digest('hex');
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const content = stamp(await verifierFingerprint());
  const output = resolve(root, 'src/cloudflare/verifier-identity.ts');
  if (process.argv[2] === '--write') await writeFile(output, content);
  else if (await readFile(output, 'utf8') !== content) throw new Error('Verifier source changed. Run npm run verifier:stamp and verify again before building.');
}
